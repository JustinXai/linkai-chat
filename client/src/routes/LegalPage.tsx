export default function LegalPage() {
  const { page } = useParams();
  const pageKey = page || 'terms';
  const pageData = LEGAL_PAGES[pageKey] || LEGAL_PAGES.terms;

  return (
    <div className="flex h-full flex-col">
      <div className="border-b border-border-medium bg-white px-4 py-6">
        <h1 className="text-2xl font-semibold text-text-primary">{pageData.title}</h1>
      </div>
      <div className="flex-1 overflow-auto p-4 md:p-6 lg:p-8">
        <div className="mx-auto max-w-3xl">
          <div className="rounded-lg border border-border-medium bg-white p-4 md:p-6 lg:p-8">
            {pageData.content.map((paragraph, index) => {
              if (paragraph === '') {
                return <div key={index} className="h-4" />;
              }
              if (paragraph.startsWith('**') && paragraph.endsWith('**')) {
                return (
                  <h2 key={index} className="mb-4 mt-6 text-lg font-semibold text-text-primary first:mt-0">
                    {paragraph.replace(/\*\*/g, '')}
                  </h2>
                );
              }
              const parts = paragraph.split(/(\*\*.*?\*\*)/g);
              return (
                <p key={index} className="mb-3 leading-relaxed text-text-secondary">
                  {parts.map((part, i) => {
                    if (part.startsWith('**') && part.endsWith('**')) {
                      return <strong key={i} className="font-medium text-text-primary">{part.replace(/\*\*/g, '')}</strong>;
                    }
                    return part;
                  })}
                </p>
              );
            })}
          </div>
        </div>
      </div>
    </div>
  );
}
